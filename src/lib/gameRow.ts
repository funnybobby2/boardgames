import { Game } from "../types/Game"

/**
 * Single source of truth for the mapping between Game fields (camelCase)
 * and the `games` table columns (snake_case) in Supabase.
 * `satisfies` makes TypeScript fail if a Game field is missing here.
 */
export const GAME_COLUMNS = {
  id: "id",
  title: "title",
  group: "group",
  nbUserMin: "nb_user_min",
  nbUserMax: "nb_user_max",
  duration: "duration",
  ageMin: "age_min",
  isPlayed: "is_played",
  category: "category",
  resume: "resume",
  ruleVideoUrl: "rule_video_url",
  img: "img",
  note: "note",
  isExtension: "is_extension",
  forSale: "for_sale",
} as const satisfies Record<keyof Game, string>

type GameField = keyof typeof GAME_COLUMNS

/** Database row -> Game */
export function toGame(row: Record<string, unknown>): Game {
  const game = Object.fromEntries(
    Object.entries(GAME_COLUMNS).map(([field, column]) => [field, row[column]])
  ) as Game
  return { ...game, category: game.category ?? [] }
}

/**
 * Game (or partial Game) -> database row, for insert/update.
 * `id` is never written (generated by the database) and undefined fields are skipped.
 */
export function toRow(game: Partial<Game>): Record<string, unknown> {
  return Object.fromEntries(
    Object.entries(game)
      .filter(([field, value]) => field in GAME_COLUMNS && field !== "id" && value !== undefined)
      .map(([field, value]) => [GAME_COLUMNS[field as GameField], value])
  )
}
