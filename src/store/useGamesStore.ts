import { create } from "zustand"
import { supabase } from "../lib/supabase"
import { Game } from "../types/Game"
import { toGame, toRow } from "../lib/gameRow"

type GamesStore = {
  games: Game[]
  isLoaded: boolean
  error: string | null
  clearError: () => void
  loadGames: () => Promise<void>
  updateGame: (id: number, patch: Partial<Pick<Game, "note" | "isPlayed" | "forSale">>) => Promise<boolean>
  addGame: (game: Omit<Game, "id">) => Promise<string | null>
  editGame: (game: Game) => Promise<string | null>
}

export const useGamesStore = create<GamesStore>((set, get) => ({
  games: [],
  isLoaded: false,
  error: null,

  clearError: () => set({ error: null }),

  loadGames: async () => {
    const { data, error } = await supabase.from("games").select("*")
    if (error || !data) {
      set({ isLoaded: true, error: `Impossible de charger les jeux : ${error?.message ?? "réponse vide"}` })
      return
    }
    set({ games: data.map(toGame), isLoaded: true })
  },

  updateGame: async (id, patch) => {
    const previous = get().games.find(g => g.id === id)
    if (!previous) return false

    // Optimistic update
    set(state => ({
      games: state.games.map(g => g.id === id ? { ...g, ...patch } : g)
    }))

    const { error } = await supabase.from("games").update(toRow(patch)).eq("id", id)
    if (error) {
      // Rollback
      set(state => ({
        games: state.games.map(g => g.id === id ? previous : g),
        error: `Modification non enregistrée : ${error.message}`,
      }))
      return false
    }
    return true
  },

  addGame: async (game) => {
    // id is generated by the database (identity column)
    const { data, error } = await supabase.from("games").insert(toRow(game)).select().single()
    if (error) return error.message
    set(state => ({ games: [...state.games, toGame(data)] }))
    return null
  },

  editGame: async (game) => {
    const { error } = await supabase.from("games").update(toRow(game)).eq("id", game.id)
    if (error) return error.message
    set(state => ({ games: state.games.map(g => g.id === game.id ? game : g) }))
    return null
  },
}))
